students = []
courses = []
marks = {}

def input_students():
    num = int(input("Enter the number of students"))
    for i in range(num):
        s_id = input("Student ID:")
        name = input("Name:")
        dob = input("DoB: ")
        students.append((s_id, name, dob))

def input_courses():
    num = int(input("Enter the number of courses"))
    for i in range(num):
        c_id = input("Course ID:")
        name = input("Name:")
        courses.append((c_id, name))

def input_marks():
    c_id = input("Enter the course ID: ")
    marks[c_id] = {}
    for s in students:
        marks[c_id][s[0]] = float(input(f"Enter mark of student {s[1]}: "))

def list_students():
    print("Student List:", students)

def list_courses():
    print("Course List:", courses)

def show_marks():
    c_id = input("Enter Course ID to view marks: ")
    print(f"Marks for course {c_id}:", marks.get(c_id, "No marks available!"))

def main():
    while True:
        print("\n1.Input Students | 2.Input Courses | 3.Input Marks")
        print("4.List Students  | 5.List Courses  | 6.Show Marks | 0.Exit")
        choice = input("Select an option: ")

        if choice == '1': input_students()
        elif choice == '2': input_courses()
        elif choice == '3': input_marks()
        elif choice == '4': list_students()
        elif choice == '5': list_courses()
        elif choice == '6': show_marks()
        elif choice == '0': break

main()